// gen_zhtables 根据 OpenCC 的字符级转换词典生成"仅简体字"与"仅繁体字"两张表，输出 zhtables.go。
//
// 用法（在 core/langdetect 目录下）：
//
//	go run gen_zhtables.go -st <STCharacters.txt> -ts <TSCharacters.txt>
//
// 词典来自 OpenCC（https://github.com/BYVoid/OpenCC，Apache-2.0），
// 当前生成所用的副本取自 github.com/liuzl/gocc@v0.0.0-20231231122217-0372e1059ca5 的 dictionary 目录。
//
// 规则（ST = 简→繁，TS = 繁→简，每行"键<TAB>候选1 候选2 ..."）：
//
//	仅简体 = { k ∈ ST 的键 : k 为单字、k 不在 ST[k] 中、k 不是 TS 的键 }
//	仅繁体 = { k ∈ TS 的键 : k 为单字、k 不在 TS[k] 中、k 不是 ST 的键 }
//
// OpenCC 对简繁共用字会把自身列为候选（如 "后 → 後 后"），因此这些字被正确排除。
// 注意：仓库的 purity_test 也会解析本文件，因此出错时直接 panic，不使用 log/fmt.Print。
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"
	"unicode/utf8"
)

func main() {
	st := flag.String("st", "", "OpenCC STCharacters.txt 路径")
	ts := flag.String("ts", "", "OpenCC TSCharacters.txt 路径")
	out := flag.String("o", "zhtables.go", "输出文件")
	flag.Parse()
	if *st == "" || *ts == "" {
		panic("必须同时指定 -st 与 -ts")
	}
	stMap := load(*st)
	tsMap := load(*ts)

	simp := only(stMap, tsMap)
	trad := only(tsMap, stMap)

	var b strings.Builder
	b.WriteString("// Code generated by gen_zhtables.go; DO NOT EDIT.\n\n")
	b.WriteString("// 本文件的数据派生自 OpenCC（Open Chinese Convert，https://github.com/BYVoid/OpenCC）\n")
	b.WriteString("// 的 STCharacters.txt 与 TSCharacters.txt。\n")
	b.WriteString("// OpenCC 版权所有 (c) BYVoid 及其贡献者，依 Apache License 2.0 授权：\n")
	b.WriteString("// http://www.apache.org/licenses/LICENSE-2.0\n")
	b.WriteString("// 本文件仅保留由词典推导出的\"仅简体\"/\"仅繁体\"单字集合，生成规则见 gen_zhtables.go。\n\n")
	b.WriteString("package langdetect\n\n")
	fmt.Fprintf(&b, "// simpOnlyChars 是仅出现在简体中文中的汉字（%d 个，按码点升序）。\n", len(simp))
	writeConst(&b, "simpOnlyChars", simp)
	fmt.Fprintf(&b, "\n// tradOnlyChars 是仅出现在繁体中文中的汉字（%d 个，按码点升序）。\n", len(trad))
	writeConst(&b, "tradOnlyChars", trad)
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}

// load 读取 OpenCC 词典：键 → 候选集合。
func load(path string) map[string][]string {
	f, err := os.Open(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	m := map[string][]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, vals, ok := strings.Cut(line, "\t")
		if !ok {
			continue
		}
		m[key] = append(m[key], strings.Fields(vals)...)
	}
	if err := sc.Err(); err != nil {
		panic(err)
	}
	return m
}

// only 返回 from 中只属于本侧的单字（排序后）。
func only(from, other map[string][]string) []rune {
	var out []rune
	for k, vals := range from {
		if utf8.RuneCountInString(k) != 1 || slices.Contains(vals, k) {
			continue
		}
		if _, ok := other[k]; ok {
			continue
		}
		r, _ := utf8.DecodeRuneInString(k)
		out = append(out, r)
	}
	slices.Sort(out)
	return out
}

// writeConst 把字符集合写成按行拼接的字符串常量，每行 40 字。
func writeConst(b *strings.Builder, name string, rs []rune) {
	fmt.Fprintf(b, "const %s = \"\" +\n", name)
	for i := 0; i < len(rs); i += 40 {
		end := min(i+40, len(rs))
		sep := " +"
		if end == len(rs) {
			sep = ""
		}
		fmt.Fprintf(b, "\t%q%s\n", string(rs[i:end]), sep)
	}
}
